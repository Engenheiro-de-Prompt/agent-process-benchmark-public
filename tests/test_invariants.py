"""Independent fixture audits and negative business mutations.

No expected answer is generated by production code. Literal expectations below
were authored separately; these checks audit the hand-authored oracle file.
"""
import copy
import csv
import io
import json
from pathlib import Path
import tempfile
import unittest

from processbench import build_controls, load_cases, verify

ROOT = Path(__file__).resolve().parents[1]
CASES = json.loads((ROOT / 'cases/catalog.json').read_text(encoding='utf-8'))
ORACLES = json.loads((ROOT / 'tests/oracles.json').read_text(encoding='utf-8'))
BY_ID = {c['case_id']: c for c in CASES}


class OracleInvariantTests(unittest.TestCase):
    def test_finance_hand_calculated_snapshots_and_conservation(self):
        snapshots = {
            'finance-01': [('T1', 1001, 1000, 1, ['B1','L1']),
                           ('T3', -201, -201, 0, ['B2','L3'])],
            'finance-02': [('T1', 150, 150, 0, ['B1','L2'])],
            'finance-03': [('T1', 250, 0, 250, ['L1']),
                           ('T2', 0, -75, 75, ['B1']),
                           ('T3', 0, 0, 0, ['B2','L2'])],
            'finance-04': [],
        }
        totals = {'finance-01':(800,799,1), 'finance-02':(150,150,0),
                  'finance-03':(250,-75,325), 'finance-04':(0,0,0)}
        for cid, snapshot in snapshots.items():
            oracle = ORACLES[cid]
            rows = oracle['balances']
            self.assertEqual([(r['id'],r['ledger_cents'],r['bank_cents'],
                               r['difference_cents'],r['evidence']) for r in rows], snapshot)
            self.assertEqual(tuple(oracle['totals'][k] for k in
                             ('ledger_cents','bank_cents','difference_cents')), totals[cid])
            for key in ('ledger_cents','bank_cents','difference_cents'):
                self.assertEqual(oracle['totals'][key], sum(r[key] for r in rows))
            for row in rows:
                self.assertEqual(row['difference_cents'], row['ledger_cents']-row['bank_cents'])
                self.assertEqual(row['evidence'], sorted(set(row['evidence'])))
                for key in ('ledger_cents','bank_cents','difference_cents'):
                    self.assertIs(type(row[key]), int)

    def test_finance_evidence_points_to_confirmed_latest_nonduplicate_rows(self):
        for case in CASES[:4]:
            oracle = ORACLES[case['case_id']]
            for side in ('ledger', 'bank'):
                rows = list(csv.DictReader(io.StringIO(case['input'][side+'_csv'])))
                for output in oracle['balances']:
                    candidates = [r for r in rows if r['id'] == output['id']]
                    if candidates:
                        newest = max(int(r['revision']) for r in candidates)
                        first = next(r for r in candidates if int(r['revision']) == newest)
                        active = first['status'] == 'confirmed'
                    else:
                        active = False
                    self.assertEqual(output[side+'_cents'], int(first['amount_cents']) if active else 0)
                    side_ids = [r['row_id'] for r in rows if r['row_id'] in output['evidence']]
                    self.assertEqual(side_ids, [first['row_id']] if active else [])

    def test_meeting_exact_accepted_owner_scope_and_literal_fields(self):
        selected = {'meeting-01':['S1'], 'meeting-02':['S1','S2'],
                    'meeting-03':['S3'], 'meeting-04':[]}
        for cid, ids in selected.items():
            rows = ORACLES[cid]['obligations']
            self.assertEqual([r['id'] for r in rows], ids)
            source = {r['id']:r for r in BY_ID[cid]['input']['statements']}
            self.assertEqual(ids, sorted(r['id'] for r in source.values()
                if r['decision']=='accepted' and r['owner'] is not None))
            for row in rows:
                statement = source[row['id']]
                for key in ('action','owner','deadline'):
                    self.assertEqual(row[key], statement[key])
                self.assertEqual(row['evidence'], [row['id']])
        self.assertIsNone(ORACLES['meeting-02']['obligations'][0]['deadline'])
        self.assertEqual(ORACLES['meeting-02']['obligations'][1]['deadline'], 'na próxima terça')

    def test_inventory_hand_calculated_units_and_complete_evidence(self):
        snapshots = {
            'inventory-01':[('SKU-A',10,-1,9,['M1','M2'])],
            'inventory-02':[('SKU-A',2,-1,1,['M1']),('SKU-B',0,7,7,['M2'])],
            'inventory-03':[('SKU-A',8,0,8,['M1','M2','M3','M4'])],
            'inventory-04':[('SKU-A',0,0,0,[]),('SKU-B',5,0,5,[])],
        }
        for cid, snapshot in snapshots.items():
            rows = ORACLES[cid]['items']
            self.assertEqual([(r['sku'],r['opening_units'],r['net_units'],
                               r['closing_units'],r['evidence']) for r in rows], snapshot)
            movements = BY_ID[cid]['input']['movements']
            self.assertEqual([r['sku'] for r in rows], sorted(r['sku'] for r in BY_ID[cid]['input']['opening']))
            for row in rows:
                self.assertEqual(row['closing_units'], row['opening_units']+row['net_units'])
                self.assertEqual(row['evidence'], sorted({m['id'] for m in movements
                                  if m['sku']==row['sku'] and m['status']=='confirmed'}))
                for key in ('opening_units','net_units','closing_units'):
                    self.assertIs(type(row[key]), int)


class NegativeMutationTests(unittest.TestCase):
    def reject(self, cid, candidate):
        result = verify(BY_ID[cid], candidate, ORACLES[cid])
        self.assertFalse(result['passed'], cid)
        self.assertTrue(result['reason_codes'])

    def test_counting_revisions_or_duplicate_payment_is_rejected(self):
        for amount in (250, 300):
            candidate = copy.deepcopy(ORACLES['finance-02'])
            candidate['balances'][0]['ledger_cents'] = amount
            candidate['balances'][0]['difference_cents'] = amount-150
            candidate['totals']['ledger_cents'] = amount
            candidate['totals']['difference_cents'] = amount-150
            self.reject('finance-02', candidate)

    def test_resurrecting_cancelled_revision_is_rejected(self):
        candidate = {'balances':[{'id':'T1','ledger_cents':900,'bank_cents':0,
            'difference_cents':900,'evidence':['L1']}],
            'totals':{'ledger_cents':900,'bank_cents':0,'difference_cents':900}}
        self.reject('finance-04', candidate)

    def test_float_centavos_and_boolean_zero_are_rejected(self):
        for value in (0.0, False, '0'):
            candidate = copy.deepcopy(ORACLES['finance-03'])
            candidate['balances'][2]['ledger_cents'] = value
            self.reject('finance-03', candidate)

    def test_zero_transaction_cannot_be_omitted(self):
        candidate = copy.deepcopy(ORACLES['finance-03'])
        candidate['balances'].pop()
        self.reject('finance-03', candidate)

    def test_evidence_cannot_cite_old_revision_or_duplicate(self):
        for evidence in (['B1','L1'], ['B1','L3'], ['B1','L2','L2'], ['L2','B1']):
            candidate = copy.deepcopy(ORACLES['finance-02'])
            candidate['balances'][0]['evidence'] = evidence
            self.reject('finance-02', candidate)

    def test_acceptance_without_owner_cannot_get_invented_owner(self):
        candidate = copy.deepcopy(ORACLES['meeting-03'])
        candidate['obligations'].insert(0, {'id':'S1', 'action':'Publicar tabela sintética',
            'owner':'Pessoa-A','deadline':'2030-05-01','evidence':['S1']})
        self.reject('meeting-03', candidate)

    def test_proposal_cannot_be_promoted_even_when_nothing_is_accepted(self):
        candidate = {'obligations':[{'id':'S1','action':'Sugerir piloto fictício',
            'owner':'Pessoa-A','deadline':'amanhã','evidence':['S1']}]}
        self.reject('meeting-04', candidate)

    def test_missing_deadline_cannot_be_invented(self):
        candidate = copy.deepcopy(ORACLES['meeting-02'])
        candidate['obligations'][0]['deadline'] = '2030-04-03'
        self.reject('meeting-02', candidate)

    def test_pending_and_cancelled_inventory_cannot_be_applied(self):
        for index, net, closing in ((0,6,6),(1,-5,0)):
            candidate = copy.deepcopy(ORACLES['inventory-04'])
            candidate['items'][index]['net_units'] = net
            candidate['items'][index]['closing_units'] = closing
            self.reject('inventory-04', candidate)

    def test_reversal_keeps_original_and_reversal_as_evidence(self):
        candidate = copy.deepcopy(ORACLES['inventory-03'])
        candidate['items'][0]['evidence'] = ['M2','M4']
        self.reject('inventory-03', candidate)

    def test_units_are_not_packages(self):
        candidate = copy.deepcopy(ORACLES['inventory-01'])
        candidate['items'][0]['net_units'] = 32
        candidate['items'][0]['closing_units'] = 42
        self.reject('inventory-01', candidate)

    def test_matching_corrupted_oracle_and_candidate_does_not_pass(self):
        for cid, key, field in (('finance-01','balances','ledger_cents'),
                               ('meeting-01','obligations','owner'),
                               ('inventory-01','items','closing_units')):
            corrupted = copy.deepcopy(ORACLES[cid])
            corrupted[key][0][field] = 'CORRUPTED'
            result = verify(BY_ID[cid], corrupted, corrupted)
            self.assertEqual(result['reason_codes'], ['INVALID_ORACLE'])
            self.assertEqual(build_controls(BY_ID[cid], corrupted), [])

    def test_loader_malformed_catalog_is_atomic_and_never_reads_oracles(self):
        # All ephemeral writes stay within the explicitly authorized tests tree.
        with tempfile.TemporaryDirectory(prefix='fixture-', dir=ROOT / 'tests') as tmp:
            directory = Path(tmp) / 'cases'
            directory.mkdir()
            contracts = (ROOT / 'cases/contracts.json').read_text(encoding='utf-8')
            (directory / 'contracts.json').write_text(contracts, encoding='utf-8')
            catalog = directory / 'catalog.json'
            for content in ('{', 'null', '{}', '[null]', json.dumps([CASES[0], CASES[0]])):
                catalog.write_text(content, encoding='utf-8')
                self.assertEqual(load_cases(tmp), [])
            catalog.write_text(json.dumps(CASES), encoding='utf-8')
            # There is deliberately no tests/oracles.json in this fixture root.
            self.assertEqual(len(load_cases(tmp)), 12)


if __name__ == '__main__':
    unittest.main()
